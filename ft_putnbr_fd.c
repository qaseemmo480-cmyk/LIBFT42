#include "libft.h"

void	ft_putnbr_fd(int n, int fd)
{
	char	cc;

	if (n == -2147483648)
	{
		write(fd, "-2147483648", 11);
		return ;
	}
	cc = n + '0';
	if (n < 0)
	{
		write(fd, "-", 1);
		n *= -1;
	}
	if (n >= 10)
	{
		ft_putnbr_fd(n / 10, fd);
		ft_putnbr_fd(n % 10, fd);
	}
	else
		write(fd, &cc, 1);
}
